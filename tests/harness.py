"""Общее для проверок: тихие окна и ожидание сервера.

Проверок много, и раньше каждая оконная поднимала настоящее окно поверх
всего, что было на экране, — работать в это время было нельзя. Окна никуда
не делись, они по-прежнему настоящие и живые: просто уехали за край экрана.

Прозрачность (-alpha 0) для этого не годится: прозрачное окно перестаёт
быть «тем, что под указателем», и проверки колеса и прокрутки перестают
находить, что листать. А уехавшее за край — находят: Tk считает попадание
по своим же записям о расположении, а не спрашивает систему.

Показать их обратно можно переменной VELIX_SHOW_WINDOWS=1 — например, когда
нужны снимки экрана из tests/shots.
"""

import os
import socket
import time

ТИХО = os.environ.get("VELIX_SHOW_WINDOWS") != "1"


def тихое_окно(app):
    """Готовит окно проверки: прозрачное и не поверх всех."""
    if not ТИХО:
        app.attributes("-topmost", True)
        return

    # Далеко влево и вверх: там его не видно, но для Tk оно на месте
    app.geometry("+-3000+-3000")


def дождаться(port, host="localhost", предел=25):
    """Ждёт, пока сервер начнёт слушать порт.

    Раньше тут стояло «поспать две с половиной секунды» — с запасом на
    медленную машину. На быстрой это чистое ожидание, и на семьдесят с
    лишним проверок набегали минуты. Порт отвечает сразу, как только сервер
    поднялся, так что спрашиваем его, а не часы.
    """
    конец = time.monotonic() + предел
    while time.monotonic() < конец:
        try:
            with socket.create_connection((host, int(port)), timeout=0.3) as связь:
                # Просто открыть и закрыть связь нельзя: сервер сочтёт это
                # оборванным рукопожатием и напишет об этом в журнал, а
                # проверки этот журнал читают. Здороваемся по-человечески —
                # обычным запросом, на который он ответит отказом без ругани
                связь.sendall(b"GET / HTTP/1.1\r\nHost: velix\r\n\r\n")
                связь.settimeout(1.0)
                try:
                    связь.recv(64)
                except OSError:
                    pass
                return True
        except OSError:
            time.sleep(0.05)
    return False
