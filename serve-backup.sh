#!/bin/sh
# Отдаёт копию переписки тому, кто пришёл за ней по ключу для копий.
#
# Копии тянет к себе домашний сервер, а не малина толкает их наружу. Так
# правильнее: малина смотрит в интернет, и ключей от сервера копий у неё нет —
# случись что, копии останутся целы.
#
# Ключ сервера копий заперт этим скриптом: что бы он ни попросил, выполнится
# только то, что здесь написано. В ~/.ssh/authorized_keys на малине строка
# выглядит так (одной строкой):
#
#   from="192.168.0.100",restrict,command="/home/vexorter/velix/serve-backup.sh"
#   ssh-ed25519 AAAA... velix-backup
#
# Что умеет:
#   list          — какие копии есть
#   latest        — самая свежая, одним потоком tar (это же и по умолчанию)
#   <имя>         — названная копия
#   report <что>  — отметиться в журнале, что копия уехала

set -e

BACKUP_DIR="${BACKUP_DIR:-$HOME/velix-backups}"
WHAT="${SSH_ORIGINAL_COMMAND:-latest}"

newest() {
    ls -1d "$BACKUP_DIR"/*/ 2>/dev/null | sed 's:/*$::' | sort | tail -1
}

give() {
    NAME=$1
    [ -d "$BACKUP_DIR/$NAME" ] || { echo "нет такой копии: $NAME" >&2; exit 1; }
    # Имя копии уходит в stderr: тот, кто тянет, увидит его в своём журнале
    echo "отдаём $NAME" >&2
    tar -C "$BACKUP_DIR" -cf - "$NAME"
}

ACTION=${WHAT%% *}
REST=${WHAT#* }
[ "$REST" = "$WHAT" ] && REST=""

case "$ACTION" in
    report)
        # Домашний сервер отчитывается, что копию забрал. В журнал пускаем
        # только безобидное: сторож потом смотрит, не молчит ли он неделю
        # Пришедшее с той стороны в журнал как есть не пускаем: берём оттуда
        # только имя копии и число, а фразу складываем уже здесь
        set -- $REST
        WHICH=$(printf '%s' "${1:-?}" | tr -cd 'A-Za-z0-9_.:-' | cut -c1-64)
        HOW=$(printf '%s' "${2:-0}" | tr -cd '0-9' | cut -c1-9)
        LOG="$HOME/velix/backup-pull.log"
        printf '%s привезли %s, сообщений %s\n' "$(date '+%Y-%m-%d %H:%M')" \
            "${WHICH:-неизвестно}" "${HOW:-0}" >> "$LOG"
        tail -n 500 "$LOG" > "$LOG.short" && mv "$LOG.short" "$LOG"
        ;;
    list)
        # Сначала снимаем косую черту в конце, потом уже дорожку: наоборот
        # жадная точка съедала бы и её, оставляя пустые строки
        ls -1d "$BACKUP_DIR"/*/ 2>/dev/null | sed 's:/*$::;s:.*/::' | sort
        ;;
    latest|"")
        NEWEST=$(newest)
        [ -n "$NEWEST" ] || { echo "копий ещё нет" >&2; exit 1; }
        give "$(basename "$NEWEST")"
        ;;
    *)
        # basename отрезает любые дорожки наружу: ../../ сюда не проедет
        give "$(basename "$ACTION")"
        ;;
esac
